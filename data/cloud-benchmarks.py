def get_benchmarks_by_provider(provider):
    """Get benchmarks for a specific cloud provider."""
    providers = {
        "aws": AWS_CIS_BENCHMARKS,
        "azure": AZURE_CIS_BENCHMARKS,
        "gcp": GCP_CIS_BENCHMARKS,
    }
    return providers.get(provider.lower(), [])


def get_benchmarks_by_section(provider, section):
    """Get benchmarks filtered by section for a provider."""
    benchmarks = get_benchmarks_by_provider(provider)
    return [b for b in benchmarks if b.get("section", "").lower() == section.lower()]


def get_total_checks():
    """Return total number of benchmark checks across all providers."""
    return {
        "aws": len(AWS_CIS_BENCHMARKS),
        "azure": len(AZURE_CIS_BENCHMARKS),
        "gcp": len(GCP_CIS_BENCHMARKS),
        "total": len(AWS_CIS_BENCHMARKS) + len(AZURE_CIS_BENCHMARKS) + len(GCP_CIS_BENCHMARKS),
    }


