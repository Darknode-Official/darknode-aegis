def search_artifacts(keyword):
    """Search all artifacts by keyword."""
    results = []
    all_artifacts = (
        [{"os": "Windows", **a} for a in WINDOWS_REGISTRY_ARTIFACTS] +
        [{"os": "Windows", **a} for a in WINDOWS_FILESYSTEM_ARTIFACTS] +
        [{"os": "Windows", "category": "Event Log", "artifact": f"Event {a['event_id']}", **a}
         for a in WINDOWS_EVENT_LOG_ARTIFACTS] +
        [{"os": "Linux", **a} for a in LINUX_FILESYSTEM_ARTIFACTS]
    )
    keyword_lower = keyword.lower()
    for artifact in all_artifacts:
        searchable = json.dumps(artifact, default=str).lower()
        if keyword_lower in searchable:
            results.append(artifact)
    return results


