def get_payloads(attack_type, subtype=None):
    """Get payloads for a given attack type and optional subtype."""
    if attack_type not in ATTACK_PAYLOADS:
        return []
    data = ATTACK_PAYLOADS[attack_type]
    if isinstance(data, list):
        return data
    if subtype and subtype in data:
        return data[subtype]
    if isinstance(data, dict):
        all_payloads = []
        for v in data.values():
            if isinstance(v, list):
                all_payloads.extend(v)
        return all_payloads
    return []

